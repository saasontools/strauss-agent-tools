/** A generator confirming its own record adds no independent check. */
export class KbSelfVerificationError extends BaseError {
  constructor(
    readonly conceptId: string,
    readonly actor: string,
    readonly generatedBy: string,
  ) {
    super({
      message: `kb: ${conceptId} was generated by ${generatedBy}, and a record's generator cannot verify it — only a human or a different actor can`,
      errorType: ErrorTypes.KbSelfVerification,
      code: 400,
      fault: Fault.User,
      retriable: false,
      reportToUser: true,
      details: { conceptId, actor, generatedBy, action: "refused" },
    });
  }
}

/**
 * A pack that will not fit its token budget. Refusal, not truncation: a
 * partial pack is indistinguishable from a complete one, so the caller gets
 * the full picture — how many records, how many tokens, and every id the
 * walk's own limits already cut — and decides whether to raise the budget or
 * tighten the walk.
 */
export class KbPackBudgetExceededError extends BaseError {
  constructor(
    readonly recordCount: number,
    readonly approxTokens: number,
    readonly budgetTokens: number,
    readonly excluded: string[],
  ) {
    super({
      message: `kb: a pack of ${recordCount} records is ~${approxTokens} tokens against a budget of ${budgetTokens} — lower hops or maxNodes, or raise the budget`,
      errorType: ErrorTypes.KbPackBudgetExceeded,
      code: 400,
      fault: Fault.User,
      retriable: false,
      reportToUser: true,
      details: { recordCount, approxTokens, budgetTokens, excluded },
    });
  }
}

/**
 * A `rels` option naming something the walk can never follow.
 *
 * Refused rather than ignored: dropping an unrecognised rel would return an
 * empty impact set — "nothing breaks" — indistinguishable from a genuine
 * result. `related_to` is refused here too, since it asserts no dependence and
 * following it can only produce that same empty set.
 */
export class KbUnknownLinkRelError extends BaseError {
  constructor(
    readonly rel: string,
    readonly expected: readonly string[],
  ) {
    super({
      message: `kb: ${rel} is not a rel a walk can follow — expected one of ${expected.join(", ")}`,
      errorType: ErrorTypes.KbUnknownLinkRel,
      code: 400,
      fault: Fault.User,
      retriable: false,
      reportToUser: true,
      details: { rel, expected: expected.join(", ") },
    });
  }
}

/**
 * A flag that takes a value, given none.
 *
 * `strauss-kb load --budget` used to read the next argv entry, find
 * nothing, and quietly fall back to the default — so a caller who meant to
 * raise a ceiling got the ceiling they were trying to move, and a typo looked
 * exactly like success. Refusing is the only way that stays visible.
 */
export class KbMissingFlagValueError extends BaseError {
  constructor(readonly flag: string) {
    super({
      message: `kb: ${flag} needs a value — pass ${flag} <value> or ${flag}=<value>`,
      errorType: ErrorTypes.KbMissingFlagValue,
      code: 400,
      fault: Fault.User,
      retriable: false,
      reportToUser: true,
      details: { flag },
    });
  }
}

