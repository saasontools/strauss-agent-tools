import { describe, expect, test } from "vitest";
import type { KbAnchor, KbRecord } from "../kb-record.schema.js";
import { classifyDiff } from "./classify.js";
import { PATH_RULES, type KbClass, type KbClassifyFile } from "./index.js";

function file(
  filePath: string,
  rest: Partial<KbClassifyFile> = {},
): KbClassifyFile {
  return { filePath, hunks: [], ...rest };
}

function classOf(input: KbClassifyFile, records: KbRecord[] = []): KbClass {
  return (classifyDiff([input], { records })[0] as { class: KbClass }).class;
}

function override(
  conceptId: string,
  tag: string,
  anchors: KbAnchor[],
  frontmatter: Partial<KbRecord["frontmatter"]> = {},
): KbRecord {
  return {
    conceptId,
    frontmatter: {
      type: "fact",
      strauss_status: "accepted",
      tags: ["review", tag],
      generated: { by: "test", at: "2026-08-01T00:00:00Z" },
      strauss_anchors: anchors,
      ...frontmatter,
    } as KbRecord["frontmatter"],
    body: "Body.",
  };
}

