#!/usr/bin/env node
/**
 * PreToolUse hook: denies direct Write/Edit/MultiEdit edits to the files a
 * KB bundle's write path (kb_write, kb_supersede, ...) generates and owns —
 * INDEX.md, log.jsonl, and the search index. Hand-editing one only creates
 * drift: the next store write recomputes and overwrites it, silently
 * dropping whatever the edit changed.
 *
 * Independent of STRAUSS_KB_NO_VALIDATE_HOOK — that variable names the
 * *validate* hook specifically, and this check is a different kind of
 * cheap: one basename comparison against a fixed set, no CLI shelled out,
 * nothing worth an opt-out for cost. A project that genuinely needs to
 * hand-edit a generated file disables this hook the ordinary way (Claude
 * Code's own hook settings), not through that env var.
 *
 * Fails open: any unexpected input allows the tool call through untouched,
 * same as the rest of this plugin's hooks — this only ever *adds* a deny
 * decision, never removes the normal permission flow.
 */
import { readFileSync } from "node:fs";
import { basename, isAbsolute, resolve } from "node:path";
import { findBundleRoot, STORE_OWNED_BASENAMES } from "./kb-bundle.mjs";

function main() {
  let input;
  try {
    input = JSON.parse(readFileSync(0, "utf8"));
  } catch {
    return 0;
  }

  const filePath = input?.tool_input?.file_path;
  if (typeof filePath !== "string" || !filePath) return 0;

  const cwd =
    typeof input?.cwd === "string" && input.cwd ? input.cwd : process.cwd();
  const absolute = isAbsolute(filePath) ? filePath : resolve(cwd, filePath);

  const bundleRoot = findBundleRoot(absolute);
  if (!bundleRoot) return 0;

  const name = basename(absolute);
  if (!STORE_OWNED_BASENAMES.has(name)) return 0;

  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "PreToolUse",
        permissionDecision: "deny",
        permissionDecisionReason:
          `${name} is generated by the KB store's write path (kb_write, ` +
          `kb_supersede, ...) inside ${bundleRoot} — a direct edit will be ` +
          "overwritten and can desync from the records it summarizes. Edit " +
          "the underlying record file instead, or write through the " +
          "CLI/MCP tools.",
      },
    }),
  );
  return 0;
}

process.exit(main());
